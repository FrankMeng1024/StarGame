// Map magnitude to pixel radius
export function magToRadius(mag) {
  if (mag <= 0.5) return 18;
  if (mag <= 1.0) return 15;
  if (mag <= 1.5) return 13;
  if (mag <= 2.0) return 11;
  if (mag <= 2.5) return 9;
  if (mag <= 3.0) return 7;
  if (mag <= 4.0) return 5;
  return 4;
}

// Map spectral type to color
export function typeToColor(type) {
  const map = {
    O: '#9bb0ff', B: '#aabfff', A: '#cad7ff',
    F: '#f8f7ff', G: '#fff4e8', K: '#ffd2a1', M: '#ffcc6f', C: '#ff8040',
  };
  return map[type] || '#e8e8f0';
}
